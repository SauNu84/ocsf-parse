#!/usr/bin/env python3
"""Run `ocsf-mapper benchmark` against every mapping × its pinned sample.

Emits BENCHMARKS.md at the repo root. Re-runnable; deterministic up to
real-world wall-clock variance.

    python scripts/run_benchmarks.py [--seconds 1.0] [--min-events 2000]
"""

from __future__ import annotations

import argparse
import json
import platform
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from ocsf_mapper.benchmark import benchmark
from ocsf_mapper.registry import list_mappings
from ocsf_mapper._fastjson import HAS_ORJSON


def _fmt_int(n: float) -> str:
    return f"{int(n):,}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seconds", type=float, default=1.0,
                    help="Per-mapping wall-time cap (default 1.0).")
    ap.add_argument("--min-events", type=int, default=2_000,
                    help="Per-mapping minimum event count before reporting.")
    ap.add_argument("--out", default="BENCHMARKS.md",
                    help="Markdown output path (default ./BENCHMARKS.md).")
    args = ap.parse_args()

    rows = list_mappings(REPO / "mappings")
    if not rows:
        print("no mappings found", file=sys.stderr)
        return 1

    results: list[dict] = []
    for entry in rows:
        sample = entry.get("sample")
        if not sample:
            print(f"  skip {entry['name']}: no sample", file=sys.stderr)
            continue
        cfg = json.loads(Path(entry["path"]).read_text())
        try:
            r = benchmark(cfg, sample,
                          min_events=args.min_events,
                          max_seconds=args.seconds)
        except Exception as e:  # pragma: no cover - safety net
            print(f"  fail {entry['name']}: {e!r}", file=sys.stderr)
            continue
        r["_name"] = entry["name"]
        r["_display"] = entry.get("display_name", entry["name"])
        r["_parser"] = entry.get("parser_kind", "?")
        results.append(r)
        print(f"  {entry['name']:<22}  {r['events_per_s']:>10,.0f} ev/s  "
              f"{r['bytes_per_s'] / (1024 * 1024):>6.1f} MB/s")

    md = _render_markdown(results, args)
    out_path = REPO / args.out
    out_path.write_text(md)
    print(f"\nwrote {out_path}", file=sys.stderr)
    return 0


def _render_markdown(results: list[dict], args: argparse.Namespace) -> str:
    if not results:
        return "# Benchmarks\n\n_no mappings ran successfully._\n"

    lines: list[str] = []
    lines.append("# Per-mapping throughput")
    lines.append("")
    lines.append("Generated by `scripts/run_benchmarks.py`. Single-process apply,")
    lines.append("in-memory write counter (so I/O does not skew the result).")
    lines.append("")
    lines.append("**Environment**")
    lines.append("")
    lines.append(f"- Python:    `{sys.version.split()[0]}` on `{platform.platform()}`")
    lines.append(f"- orjson:    `{HAS_ORJSON}`")
    lines.append(f"- ocsf-schema submodule HEAD: pinned (see `.gitmodules`)")
    lines.append(f"- Wall-clock cap per mapping: {args.seconds}s, min events {args.min_events}")
    lines.append(f"- Run at: {datetime.now(timezone.utc).isoformat(timespec='seconds')}")
    lines.append("")
    lines.append(f"For 10 TB-class workloads, multiply the per-source rate below")
    lines.append(f"by your worker count. See README §\"At scale\".")
    lines.append("")

    # Headline table
    lines.append("## Throughput")
    lines.append("")
    lines.append("| Source | Parser | Events/sec | MB/sec | Parse % | Route % | Map % | Write % |")
    lines.append("|---|---|---:|---:|---:|---:|---:|---:|")
    for r in sorted(results, key=lambda x: -x["events_per_s"]):
        pct = r["phase_pct"]
        lines.append(
            f"| `{r['_name']}` | {r['_parser']} "
            f"| {_fmt_int(r['events_per_s'])} "
            f"| {r['bytes_per_s'] / (1024 * 1024):.1f} "
            f"| {pct['parse']:.1f}% | {pct['route']:.1f}% "
            f"| {pct['map']:.1f}% | {pct['write']:.1f}% |"
        )
    lines.append("")

    # Aggregate
    fastest = max(results, key=lambda r: r["events_per_s"])
    slowest = min(results, key=lambda r: r["events_per_s"])
    median = sorted(results, key=lambda r: r["events_per_s"])[len(results) // 2]
    map_pct = [r["phase_pct"]["map"] for r in results]
    avg_map_pct = sum(map_pct) / len(map_pct)

    lines.append("## Headlines")
    lines.append("")
    lines.append(f"- Fastest: **`{fastest['_name']}`** at "
                 f"{int(fastest['events_per_s']):,} events/sec.")
    lines.append(f"- Slowest: **`{slowest['_name']}`** at "
                 f"{int(slowest['events_per_s']):,} events/sec.")
    lines.append(f"- Median: **`{median['_name']}`** at "
                 f"{int(median['events_per_s']):,} events/sec.")
    lines.append(f"- The `map` phase averages **{avg_map_pct:.1f}%** of total time")
    lines.append(f"  across mappings — DSL dictionary-walking dominates regardless of")
    lines.append(f"  whether the source is JSON or regex.")
    lines.append("")
    lines.append("## How to reproduce")
    lines.append("")
    lines.append("```bash")
    lines.append("python scripts/run_benchmarks.py")
    lines.append("# or per mapping:")
    lines.append("ocsf-mapper benchmark mappings/cloudtrail.json samples/cloudtrail.jsonl")
    lines.append("```")
    lines.append("")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sys.exit(main())
